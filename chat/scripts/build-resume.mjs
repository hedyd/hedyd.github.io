// Builds the resume text the chat sends to the model from the same JSON the
// site renders, so the two can't drift apart. Output: src/generated/resume.ts
// (gitignored). Runs automatically before `wrangler dev` and `wrangler deploy`.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dataDir = join(root, "..", "ui", "src", "data");
const readJson = (path) => JSON.parse(readFileSync(path, "utf-8"));
const list = (items) => items.map((item) => `- ${item}`).join("\n");

const resume = readJson(join(dataDir, "resume", "resume.json"));
const about = readJson(join(dataDir, "about", "about.json"));

// Same order as the site: newest year first, then entries without a year by
// their `order` field (see ui/src/data/sortProjects.ts).
const projectsDir = join(dataDir, "projects");
const projects = readdirSync(projectsDir)
  .filter((file) => file.endsWith(".json"))
  .map((file) => ({
    id: file.replace(/\.json$/, ""),
    ...readJson(join(projectsDir, file)),
  }))
  .sort((a, b) => {
    if (a.year != null && b.year != null)
      return b.year - a.year || a.id.localeCompare(b.id);
    if (a.year != null) return -1;
    if (b.year != null) return 1;
    return (a.order ?? 0) - (b.order ?? 0);
  });

const sections = [`${resume.name}`];

sections.push(`# About\n${about.summary.join("\n\n")}`);

sections.push(
  `# Education\n${resume.education
    .map((e) => `${e.school}\n${e.location} | ${e.date}\n${e.degree}`)
    .join("\n\n")}`,
);

sections.push(
  `# Skills\n${resume.skills
    .map((group) => `## ${group.type}\n${group.skills.join(", ")}`)
    .join("\n\n")}`,
);

sections.push(
  `# Work Experience\n${resume.experience
    .map(
      (job) =>
        `## ${job.title}, ${job.org}\n${job.location} | ${job.dates}\n${list(job.items)}`,
    )
    .join("\n\n")}`,
);

const projectText = projects.map((p) => {
  const parts = [`## ${p.title}`];
  const header = [p.job, p.year].filter(Boolean).join(" | ");
  if (header) parts.push(header);
  const summary = Array.isArray(p.summary) ? p.summary.join("\n\n") : p.summary;
  if (summary) parts.push(`\n${summary}`);
  if (p.skills?.length) parts.push(`\n### Skills\n${p.skills.join(", ")}`);
  if (p.responsibilities?.length)
    parts.push(`\n### Responsibilities\n${list(p.responsibilities)}`);
  if (p.features?.length) parts.push(`\n### Features\n${list(p.features)}`);
  for (const role of p.roles ?? []) {
    parts.push(`\n### ${role.title}, ${role.org}\n${list(role.items)}`);
  }
  return parts.join("\n");
});
sections.push(`# Projects\n${projectText.join("\n\n")}`);

const text = sections.join("\n\n");
const outDir = join(root, "src", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "resume.ts"),
  `// Generated by scripts/build-resume.mjs. Do not edit.\nexport const resume = ${JSON.stringify(text)};\n`,
);
console.log(`Wrote resume prompt (${text.length} characters).`);
